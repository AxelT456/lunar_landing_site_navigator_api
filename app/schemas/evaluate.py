"""Operational site evaluation schemas."""

from datetime import datetime
from typing import List, Literal, Optional
from pydantic import Field

from app.core.constants import (
    DEFAULT_DURATION_DAYS,
    DEFAULT_PANEL_AREA_M2,
    DEFAULT_PANEL_EFFICIENCY,
    DEFAULT_STEP_MINUTES,
    MAX_DURATION_DAYS,
    MAX_STEP_MINUTES,
    MIN_DURATION_DAYS,
    MIN_STEP_MINUTES,
)
from app.schemas.common import BaseSchema, LunarLat, LunarLon, Vector3D

OperationalStatus = Literal["GO", "NO-GO", "CAUTION"]


class EvaluateRequest(BaseSchema):
    """Request payload for operational temporal evaluation."""

    lat: LunarLat
    lon: LunarLon
    start_utc: datetime = Field(..., description="Start timestamp of mission window in ISO-8601 UTC")
    duration_days: float = Field(
        default=DEFAULT_DURATION_DAYS,
        ge=MIN_DURATION_DAYS,
        le=MAX_DURATION_DAYS,
        description=f"Evaluation duration in Earth days ({MIN_DURATION_DAYS} to {MAX_DURATION_DAYS})",
    )
    step_minutes: int = Field(
        default=DEFAULT_STEP_MINUTES,
        ge=MIN_STEP_MINUTES,
        le=MAX_STEP_MINUTES,
        description=f"Time step resolution in minutes ({MIN_STEP_MINUTES} to {MAX_STEP_MINUTES})",
    )
    panel_efficiency: float = Field(
        default=DEFAULT_PANEL_EFFICIENCY,
        ge=0.0,
        le=1.0,
        description="Solar panel conversion efficiency (0.0 to 1.0)",
    )
    panel_area_m2: float = Field(
        default=DEFAULT_PANEL_AREA_M2,
        gt=0.0,
        description="Total solar array area in square meters (> 0.0)",
    )


class SiteEvaluation(BaseSchema):
    """Site topographical status and landing safety classification."""

    lat: LunarLat
    lon: LunarLon
    elevation_m: float = Field(..., description="Landing point elevation (meters)")
    slope_deg: float = Field(..., description="Landing point slope (degrees)")
    nearest_psr_km: float = Field(..., description="Distance to nearest PSR (km)")
    status: OperationalStatus = Field(..., description="GO / NO-GO / CAUTION assessment")
    reasons: List[str] = Field(default_factory=list, description="Detailed justification list for status")


class EvaluationSummary(BaseSchema):
    """Aggregate metrics across the evaluation window."""

    sun_visible_pct: float = Field(..., description="Percentage of window with direct solar visibility (%)")
    earth_visible_pct: float = Field(..., description="Percentage of window with Direct-to-Earth visibility (%)")
    max_continuous_sun_hours: float = Field(..., description="Longest continuous period of direct sunlight (hours)")
    max_continuous_dte_hours: float = Field(..., description="Longest continuous period of Earth line-of-sight (hours)")
    next_sunset_utc: Optional[datetime] = Field(None, description="Timestamp of the first sunset event")
    hours_to_next_sunset: Optional[float] = Field(None, description="Hours remaining until the first sunset")
    next_earthset_utc: Optional[datetime] = Field(None, description="Timestamp of the first Earth-set event")
    hours_to_next_earthset: Optional[float] = Field(None, description="Hours remaining until the first Earth-set")
    avg_power_factor: float = Field(..., description="Average normalized power generation factor (0.0 to 1.0)")
    estimated_peak_power_w: float = Field(..., description="Estimated peak power generated by array (Watts)")


class HorizonProfilePoint(BaseSchema):
    """Point along the 360-degree topographical horizon mask."""

    az_deg: float = Field(..., description="Azimuth angle (0 to 360 degrees, 0 = North, 90 = East)")
    horizon_el_deg: float = Field(..., description="Horizon obstruction elevation angle (degrees)")


class TimelinePoint(BaseSchema):
    """Discrete time step ephemeris and visibility state."""

    timestamp_utc: datetime = Field(..., description="Timestamp in ISO-8601 UTC")
    sun_az_deg: float = Field(..., description="Solar azimuth angle (degrees)")
    sun_el_deg: float = Field(..., description="Solar elevation angle relative to local flat horizon (degrees)")
    sun_horizon_el_deg: float = Field(..., description="Topographic horizon elevation at sun azimuth (degrees)")
    sun_visible: bool = Field(..., description="Whether the Sun is above the terrain horizon")
    sun_vector_3d: Vector3D = Field(..., description="Unit vector pointing to Sun in 3D visor coordinates")
    earth_az_deg: float = Field(..., description="Earth azimuth angle (degrees)")
    earth_el_deg: float = Field(..., description="Earth elevation angle relative to local flat horizon (degrees)")
    earth_horizon_el_deg: float = Field(..., description="Topographic horizon elevation at Earth azimuth (degrees)")
    earth_visible: bool = Field(..., description="Whether the Earth is above the terrain horizon (DTE active)")
    earth_vector_3d: Vector3D = Field(..., description="Unit vector pointing to Earth in 3D visor coordinates")
    power_factor: float = Field(..., description="Instantaneous solar power efficiency factor (0.0 to 1.0)")


class EvaluateResponse(BaseSchema):
    """Complete temporal and operational evaluation response."""

    site: SiteEvaluation
    summary: EvaluationSummary
    horizon_profile: List[HorizonProfilePoint] = Field(default_factory=list)
    timeline: List[TimelinePoint] = Field(default_factory=list)
